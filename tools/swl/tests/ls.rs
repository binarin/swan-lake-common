//! `swl ls` on a disposable forge: a line per workspace with its stage and
//! whether `swl ws prune` would remove it, and the forge's open MRs that no
//! workspace holds, grouped by ticket ID or branch.

mod support;

use std::fs;

use support::{Forge, stdout};

/// The line of workspace `name`, its columns' padding collapsed to two
/// spaces.
fn ws_line(out: &str, name: &str) -> String {
    let want = format!("{name}  ");
    out.lines()
        .map(|l| {
            let mut l = l.trim().to_string();
            while l.contains("   ") {
                l = l.replace("   ", "  ");
            }
            l
        })
        .find(|l| l.starts_with(&want))
        .unwrap_or_else(|| panic!("no line of {name:?} in\n{out}"))
}

/// The forge section: what follows `open on the forge, in no workspace:`.
fn forge_section(out: &str) -> &str {
    out.split_once("open on the forge, in no workspace:\n")
        .unwrap_or_else(|| panic!("no forge section in\n{out}"))
        .1
}

/// The forge section's lines, trimmed, the padding collapsed.
fn forge_lines(out: &str) -> Vec<String> {
    forge_section(out)
        .lines()
        .map(|l| {
            let mut l = l.trim().to_string();
            while l.contains("   ") {
                l = l.replace("   ", "  ");
            }
            l
        })
        .collect()
}

const SHA: &str = "1111111111111111111111111111111111111111";

#[test]
fn ls_lists_each_workspace_with_its_stage_and_whether_it_is_removable() {
    let f = Forge::new("ls-local");
    // Ignored files do not keep a workspace.
    f.commit_file_on_forge("swan-lake", "master", ".gitignore", "*.log\n");
    let work = f.root.join("work");
    fs::create_dir_all(&work).unwrap();
    for name in [
        "SL-0001-clean",
        "SL-0002-dirty",
        "SL-0003-untracked",
        "SL-0004-unpushed",
        "SL-0005-ignored",
        "SL-0006-pushed",
    ] {
        stdout(&f.swl(&work, &["start", name, "swan-lake", "swan-lake-common@lib"]));
    }
    fs::create_dir(work.join("SL-0007-empty")).unwrap();
    // Two checkouts that override the same input: the workspace cannot be
    // read, the others list.
    for checkout in ["a@lib", "b@lib"] {
        let dir = work.join("SL-0008-broken").join(checkout);
        fs::create_dir_all(&dir).unwrap();
        fs::write(dir.join("flake.nix"), "{ outputs = _: { }; }\n").unwrap();
    }
    let consumer = |ws: &str| work.join(ws).join("swan-lake");
    fs::write(consumer("SL-0002-dirty").join("value.txt"), "changed").unwrap();
    fs::write(consumer("SL-0003-untracked").join("new.txt"), "new").unwrap();
    fs::write(consumer("SL-0004-unpushed").join("value.txt"), "c2").unwrap();
    f.git(&consumer("SL-0004-unpushed"), &["commit", "-qam", "c2"]);
    fs::write(consumer("SL-0005-ignored").join("build.log"), "log").unwrap();
    let pushed = consumer("SL-0006-pushed");
    fs::write(pushed.join("value.txt"), "c3").unwrap();
    f.git(&pushed, &["commit", "-qam", "c3"]);
    f.git(&pushed, &["push", "-q", "origin", "sl-0006-pushed"]);
    f.git(&pushed, &["reset", "-q", "--hard", "origin/master"]);

    // swl start's env step wrote the generated .envrc.local, which does not
    // keep a workspace.
    assert!(
        fs::read_to_string(consumer("SL-0001-clean").join(".envrc.local"))
            .unwrap()
            .starts_with("# Generated by `swl env`")
    );
    for (args, unpushed_next) in [
        (&["ls"][..], "swl publish swan-lake"),
        (
            &["ls", "--no-fetch"][..],
            "swl publish swan-lake (unless sl-0004-unpushed's MR merged: --no-fetch does not \
             look it up)",
        ),
    ] {
        let out = stdout(&f.swl(&f.root, args));
        assert!(
            out.starts_with(&format!("workspaces in {}:", work.display())),
            "{out}"
        );
        assert_eq!(
            ws_line(&out, "SL-0001-clean"),
            "SL-0001-clean  removable  no change (HEAD is in origin/master)  waits: nobody  next: -",
            "{out}"
        );
        assert_eq!(
            ws_line(&out, "SL-0004-unpushed"),
            format!("SL-0004-unpushed  local  waits: anyone  next: {unpushed_next}"),
            "{out}"
        );
        let broken = ws_line(&out, "SL-0008-broken");
        assert!(
            broken.starts_with("SL-0008-broken  unknown (two checkouts in ")
                && broken.ends_with(
                    "override the input \"lib\")  waits: nobody  next: rerun swl status"
                ),
            "{out}"
        );
        for kept in [
            "SL-0002-dirty",
            "SL-0003-untracked",
            "SL-0004-unpushed",
            "SL-0006-pushed",
            "SL-0007-empty",
            "SL-0008-broken",
        ] {
            assert!(
                !ws_line(&out, kept).contains("  removable  "),
                "{kept} is kept\n{out}"
            );
        }
        assert!(
            ws_line(&out, "SL-0005-ignored").contains("  removable  "),
            "{out}"
        );
        assert!(
            ws_line(&out, "SL-0007-empty").contains("no change (no checkouts)"),
            "{out}"
        );
    }
    let out = stdout(&f.swl(&f.root, &["ls"]));
    assert!(
        out.ends_with("no open MR on the forge that no workspace holds"),
        "{out}"
    );
}

#[test]
fn ls_groups_the_open_mrs_no_workspace_holds_by_ticket_or_branch() {
    let f = Forge::new("ls-forge");
    f.api.make_private("swan-lake");
    let keys = f.login().display().to_string();
    let work = f.root.join("work");
    fs::create_dir_all(&work).unwrap();
    stdout(&f.swl(&work, &["start", "SL-0010-x", "swan-lake"]));
    // Held: its checkout is on swan-lake#4's branch, and its swl.toml names
    // swan-lake-common#11.
    fs::write(
        work.join("SL-0010-x/swan-lake/swl.toml"),
        "[inputs.lib]\nrepo = \"swan-lake-common\"\nmr = 11\n",
    )
    .unwrap();
    let pr = |repo: &str, n: u64, state: &str, branch: &str| {
        let merged = (state == "merged").then_some(SHA);
        f.api.set_pr(repo, n, state, branch, SHA, merged);
    };
    pr("swan-lake", 4, "open", "sl-0010-x");
    pr("swan-lake-common", 11, "open", "other-x");
    pr("swan-lake", 5, "draft", "sl-0042-a");
    pr("swan-lake-common", 7, "open", "SL-42-b");
    pr("swan-lake", 6, "open", "feature-x");
    pr("zwanenzang", 2, "open", "feature-x");
    pr("swan-lake", 8, "open", "swl-bump-common");
    pr("zwanenzang", 3, "open", "zw-only");
    pr("swan-lake-common", 9, "open", "common-only");
    pr("swan-lake", 12, "merged", "sl-0050-done");
    pr("swan-lake", 13, "closed", "sl-0051-dropped");

    let ls = f.swl_env(&f.root, &["ls"], &[("SWL_FJ_KEYS", &keys)]);
    assert!(!support::text(&ls).contains(support::TOKEN));
    let out = stdout(&ls);
    assert_eq!(
        forge_lines(&out),
        [
            "SL-0042",
            "swan-lake#5  open (draft)  sl-0042-a  WIP: t",
            "swan-lake-common#7  open  SL-42-b  t",
            "swl start --from swan-lake#5",
            "common-only",
            "swan-lake-common#9  open  common-only  t",
            "swl start --from swan-lake-common#9 (only shared-repo MRs: common alone, as the consumer)",
            "feature-x",
            "swan-lake#6  open  feature-x  t",
            "zwanenzang#2  open  feature-x  t",
            "swl start --from swan-lake#6",
            "swl-bump-common",
            "swan-lake#8 (bump)  open  swl-bump-common  t",
            "swl start --from swan-lake#8",
            "zw-only",
            "zwanenzang#3  open  zw-only  t",
            "only shared-repo MRs: no consumer MR to swl start --from",
        ],
        "{out}"
    );
    // The private consumer's MRs need fj's login.
    assert!(
        f.authed_requests("swan-lake")
            .iter()
            .any(|p| p.contains("/pulls?state=open")),
        "{out}"
    );
    let anon = stdout(&f.swl(&f.root, &["ls"]));
    let lines = forge_lines(&anon);
    assert!(
        lines.iter().any(
            |l| l.starts_with("swan-lake: not read (not readable anonymously, and no fj login")
        ),
        "{anon}"
    );
    assert!(!lines.iter().any(|l| l.starts_with("swan-lake#")), "{anon}");

    // A repo that answers another error than a 404: not read, with why; the
    // other repos list.
    f.api.fail_reads("zwanenzang", 500);
    let out = stdout(&f.swl_env(&f.root, &["ls"], &[("SWL_FJ_KEYS", &keys)]));
    let lines = forge_lines(&out);
    assert!(
        lines
            .iter()
            .any(|l| l.starts_with("zwanenzang: not read (") && l.contains("500")),
        "{out}"
    );
    assert!(!lines.iter().any(|l| l.starts_with("zwanenzang#")), "{out}");
    assert!(
        lines.contains(&"swan-lake#6  open  feature-x  t".to_string()),
        "{out}"
    );

    // --no-fetch: the workspaces only, and no request to the forge.
    f.api.requests.lock().unwrap().clear();
    let out = stdout(&f.swl_env(&f.root, &["ls", "--no-fetch"], &[("SWL_FJ_KEYS", &keys)]));
    assert_eq!(
        ws_line(&out, "SL-0010-x"),
        "SL-0010-x  no change (HEAD is in origin/master)  waits: nobody  next: -",
        "{out}"
    );
    assert!(
        out.ends_with("--no-fetch: the forge is not read: its open MRs are not listed"),
        "{out}"
    );
    assert!(!out.contains("open on the forge"), "{out}");
    let seen: Vec<String> = f
        .api
        .requests
        .lock()
        .unwrap()
        .iter()
        .map(|r| r.path.clone())
        .collect();
    assert!(seen.is_empty(), "forge requests with --no-fetch: {seen:?}");
}

#[test]
fn ls_lines_of_published_workspaces_online_and_offline() {
    let f = Forge::new("ls-published");
    f.add_consumer("nixos-config");
    let work = f.root.join("work");
    fs::create_dir_all(&work).unwrap();
    stdout(&f.swl(&work, &["start", "SL-0020-pushed", "swan-lake"]));
    stdout(&f.swl(&work, &["start", "SL-0021-ci", "swan-lake"]));
    stdout(&f.swl(
        &work,
        &["start", "SL-0022-two", "swan-lake", "nixos-config"],
    ));
    stdout(&f.swl(&work, &["start", "SL-0023-held", "swan-lake"]));
    let commit = |dir: &std::path::Path, value: &str| {
        fs::write(dir.join("value.txt"), value).unwrap();
        f.git(dir, &["commit", "-qam", value]);
        f.git(dir, &["rev-parse", "HEAD"])
    };
    let open_mr = |repo: &str, n: u64, branch: &str, head: &str| {
        f.git(
            &f.forge_repo(repo),
            &["update-ref", &format!("refs/pull/{n}/head"), head],
        );
        f.api.set_pr(repo, n, "open", branch, head, None);
    };

    // Pushed, no MR.
    let pushed = work.join("SL-0020-pushed/swan-lake");
    commit(&pushed, "p2");
    f.git(&pushed, &["push", "-q", "origin", "sl-0020-pushed"]);

    // An MR with CI green.
    let ci = work.join("SL-0021-ci/swan-lake");
    let head = commit(&ci, "ci2");
    f.git(&ci, &["push", "-q", "origin", "sl-0021-ci"]);
    open_mr("swan-lake", 2, "sl-0021-ci", &head);
    f.api.set_status("swan-lake", &head, "success");

    // Two consumers: swan-lake's MR with CI green; nixos-config's MR merged
    // as rebased elsewhere and its branch deleted, while the local branch
    // was rebased onto a newer master.
    let two = work.join("SL-0022-two");
    let head = commit(&two.join("swan-lake"), "two2");
    f.git(
        &two.join("swan-lake"),
        &["push", "-q", "origin", "sl-0022-two"],
    );
    open_mr("swan-lake", 3, "sl-0022-two", &head);
    f.api.set_status("swan-lake", &head, "success");
    let nixos = two.join("nixos-config");
    let head = commit(&nixos, "n2");
    f.git(&nixos, &["push", "-q", "origin", "sl-0022-two"]);
    open_mr("nixos-config", 1, "sl-0022-two", &head);
    f.commit_file_on_forge("nixos-config", "master", "other.txt", "other");
    f.git(&nixos, &["fetch", "-q", "origin"]);
    f.git(&nixos, &["rebase", "-q", "origin/master"]);
    let merged = f.commit_on_forge("nixos-config", "master", "n2 rebased");
    let forge = f.forge_repo("nixos-config");
    f.git(&forge, &["update-ref", "refs/pull/1/head", &merged]);
    f.git(&forge, &["update-ref", "-d", "refs/heads/sl-0022-two"]);
    f.api.set_pr(
        "nixos-config",
        1,
        "merged",
        "refs/pull/1/head",
        &merged,
        Some(&merged),
    );

    // The consumer detached at its base, the workspace's branch MR open
    // elsewhere: the workspace holds it.
    let held = work.join("SL-0023-held/swan-lake");
    f.git(&held, &["switch", "-q", "--detach", "origin/master"]);
    f.api
        .set_pr("swan-lake", 4, "open", "sl-0023-held", SHA, None);

    let out = stdout(&f.swl(&f.root, &["ls"]));
    assert_eq!(
        ws_line(&out, "SL-0020-pushed"),
        "SL-0020-pushed  pushed  waits: anyone  next: swl publish swan-lake",
        "{out}"
    );
    assert_eq!(
        ws_line(&out, "SL-0021-ci"),
        "SL-0021-ci  CI green  waits: owner  next: merge swan-lake#2",
        "{out}"
    );
    assert_eq!(
        ws_line(&out, "SL-0022-two"),
        "SL-0022-two  CI green  waits: owner  next: merge swan-lake#3 (+ nixos-config: merged)",
        "{out}"
    );
    assert_eq!(
        ws_line(&out, "SL-0023-held"),
        "SL-0023-held  removable  not a change (detached at origin/master)  waits: anyone  next: \
         git -C swan-lake switch sl-0023-held, then swl land",
        "{out}"
    );
    assert!(
        out.ends_with("no open MR on the forge that no workspace holds"),
        "{out}"
    );
    let status = stdout(&f.swl(
        &f.root,
        &["status", "--workspace", &two.display().to_string()],
    ));
    assert!(
        status.contains("remove the workspace (nixos-config#1 of sl-0022-two is merged)"),
        "{status}"
    );

    // Offline: what needs the forge is not claimed.
    let out = stdout(&f.swl(&f.root, &["ls", "--no-fetch"]));
    let rerun =
        "pushed  waits: anyone  next: rerun without --no-fetch (it does not look up the MR)";
    assert_eq!(
        ws_line(&out, "SL-0020-pushed"),
        format!("SL-0020-pushed  {rerun}"),
        "{out}"
    );
    assert_eq!(
        ws_line(&out, "SL-0021-ci"),
        format!("SL-0021-ci  {rerun}"),
        "{out}"
    );
    assert_eq!(
        ws_line(&out, "SL-0022-two"),
        "SL-0022-two  local  waits: anyone  next: swl publish nixos-config (unless sl-0022-two's \
         MR merged: --no-fetch does not look it up) (+ swan-lake: pushed)",
        "{out}"
    );
    let status = stdout(&f.swl(
        &f.root,
        &[
            "status",
            "--workspace",
            &two.display().to_string(),
            "--no-fetch",
        ],
    ));
    assert!(
        status.contains(
            "next: swl publish nixos-config (unless sl-0022-two's MR merged: --no-fetch does not \
             look it up)"
        ),
        "{status}"
    );
}
