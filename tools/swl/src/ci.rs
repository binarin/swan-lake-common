//! `swl ci env`: a `nix` wrapper for the rest of a CI job that overrides the
//! manifest's inputs with the MRs' heads.

use std::{
    env,
    fs::{self, OpenOptions},
    io::Write,
    os::unix::fs::PermissionsExt,
    path::{Path, PathBuf},
    process::ExitCode,
};

use anyhow::{Context, Result};

use crate::{
    check::usable_mr,
    env::shell_quote,
    forge::{PrReader, pull_head_url},
    git::git,
    manifest::{MANIFEST_FILE, Manifest},
    shim::OverrideArgs,
};

/// First-line marker of the wrapper `swl ci env` writes; the shims skip
/// files with it when they look for the real tool.
pub const CI_MARKER: &str = "# Generated by `swl ci env`";

/// The overrides for the manifest's entries, or every entry's failure.
pub fn overrides(
    manifest: &Manifest,
    api: &dyn PrReader,
) -> Result<(OverrideArgs, Vec<String>), Vec<String>> {
    let mut args = Vec::new();
    let mut notes = Vec::new();
    let mut errors = Vec::new();
    for (path, entry) in &manifest.inputs {
        match usable_mr(path, entry, api.pr(&entry.repo, entry.mr)) {
            Ok((pr, note)) => {
                args.push((
                    path.clone(),
                    pull_head_url(&entry.repo, entry.mr, &pr.head_sha),
                ));
                notes.extend(note);
            }
            Err(e) => errors.push(e),
        }
    }
    if errors.is_empty() {
        Ok((args, notes))
    } else {
        Err(errors)
    }
}

pub fn wrapper(swl: &Path, flake: &Path, overrides: &OverrideArgs) -> String {
    let mut line = format!(
        "exec {} ci shim --flake {}",
        shell_quote(swl.as_os_str()),
        shell_quote(flake.as_os_str())
    );
    for (path, url) in overrides {
        line.push_str(&format!(
            " --override {} {}",
            shell_quote(path.as_ref()),
            shell_quote(url.as_ref())
        ));
    }
    format!("#!/bin/sh\n{CI_MARKER}; rerun it rather than editing.\n{line} -- \"$@\"\n")
}

fn wrapper_dir() -> Result<PathBuf> {
    let base = env::var_os("RUNNER_TEMP")
        .filter(|v| !v.is_empty())
        .map(PathBuf::from)
        .unwrap_or_else(env::temp_dir);
    for n in 0..1000 {
        let dir = base.join(format!("swl-ci-{}-{n}", std::process::id()));
        match fs::create_dir(&dir) {
            Ok(()) => return Ok(dir),
            Err(e) if e.kind() == std::io::ErrorKind::AlreadyExists => continue,
            Err(e) => return Err(e).with_context(|| format!("creating {}", dir.display())),
        }
    }
    anyhow::bail!("no free directory name under {}", base.display())
}

pub fn run_env(dir: &Path, api: &dyn PrReader, swl: &Path) -> Result<ExitCode> {
    let root = PathBuf::from(git(dir, &["rev-parse", "--show-toplevel"])?);
    let manifest = Manifest::read(&root)?.unwrap_or_default();
    if manifest.is_empty() {
        println!("swl ci env: no pending entries in {MANIFEST_FILE}; nix runs unchanged");
        return Ok(ExitCode::SUCCESS);
    }
    let (args, notes) = match overrides(&manifest, api) {
        Ok(found) => found,
        Err(errors) => {
            for e in errors {
                eprintln!("swl ci env: error: {e}");
            }
            return Ok(ExitCode::from(1));
        }
    };
    for n in notes {
        println!("swl ci env: note: {n}");
    }
    let bin = wrapper_dir()?;
    let nix = bin.join("nix");
    fs::write(&nix, wrapper(swl, &root, &args))
        .with_context(|| format!("writing {}", nix.display()))?;
    fs::set_permissions(&nix, fs::Permissions::from_mode(0o755))?;
    for (path, url) in &args {
        println!("swl ci env: --override-input {path} {url}");
    }
    match env::var_os("GITHUB_PATH").filter(|p| !p.is_empty()) {
        Some(file) => {
            OpenOptions::new()
                .append(true)
                .create(true)
                .open(&file)
                .and_then(|mut f| writeln!(f, "{}", bin.display()))
                .with_context(|| format!("appending to $GITHUB_PATH {}", file.to_string_lossy()))?;
            println!(
                "swl ci env: {} is on PATH for the job's later steps",
                nix.display()
            );
        }
        None => println!(
            "swl ci env: no $GITHUB_PATH; to use the wrapper, run\n  export PATH={}:\"$PATH\"",
            shell_quote(bin.as_os_str())
        ),
    }
    Ok(ExitCode::SUCCESS)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::{
        forge::{PrInfo, PrState},
        manifest::Entry,
    };

    struct FakeApi;

    impl PrReader for FakeApi {
        fn pr(&self, repo: &str, number: u64) -> Result<Option<PrInfo>> {
            let state = match (repo, number) {
                ("swan-lake-common", 1) => PrState::Open,
                ("swan-lake-common", 2) => PrState::Merged {
                    merge_commit: "m".into(),
                },
                ("swan-lake-common", 3) => PrState::ClosedUnmerged,
                ("offline", _) => anyhow::bail!("connection refused"),
                _ => return Ok(None),
            };
            Ok(Some(PrInfo {
                number,
                state,
                head_sha: format!("head{number}"),
                title: String::new(),
            }))
        }
    }

    fn manifest(entries: &[(&str, &str, u64)]) -> Manifest {
        Manifest {
            inputs: entries
                .iter()
                .map(|(p, r, n)| {
                    (
                        p.to_string(),
                        Entry {
                            repo: r.to_string(),
                            mr: *n,
                        },
                    )
                })
                .collect(),
        }
    }

    #[test]
    fn open_and_merged_are_overridden() {
        let (args, notes) = overrides(
            &manifest(&[
                ("common", "swan-lake-common", 1),
                ("common-next", "swan-lake-common", 2),
            ]),
            &FakeApi,
        )
        .unwrap();
        assert_eq!(args.len(), 2);
        assert_eq!(args[0].0, "common");
        assert!(
            args[0]
                .1
                .ends_with("/binarin/swan-lake-common?ref=refs/pull/1/head&rev=head1"),
            "{}",
            args[0].1
        );
        assert!(args[1].1.contains("refs/pull/2/head&rev=head2"));
        assert_eq!(notes.len(), 1);
        assert!(notes[0].contains("can land"));
    }

    #[test]
    fn closed_unknown_and_unreachable_fail() {
        let errors = overrides(
            &manifest(&[
                ("a", "swan-lake-common", 3),
                ("b", "swan-lake-common", 99),
                ("c", "offline", 1),
                ("d", "swan-lake-common", 1),
            ]),
            &FakeApi,
        )
        .unwrap_err();
        assert_eq!(errors.len(), 3, "{errors:?}");
    }

    #[test]
    fn wrapper_is_one_exec_line() {
        let w = wrapper(
            Path::new("/nix/store/x-swl/bin/swl"),
            Path::new("/ci/w s"),
            &vec![(
                "common".into(),
                "git+https://f/r?ref=refs/pull/1/head&rev=abc".into(),
            )],
        );
        assert_eq!(
            w,
            "#!/bin/sh\n# Generated by `swl ci env`; rerun it rather than editing.\n\
             exec /nix/store/x-swl/bin/swl ci shim --flake '/ci/w s' --override common \
             'git+https://f/r?ref=refs/pull/1/head&rev=abc' -- \"$@\"\n"
        );
    }
}
