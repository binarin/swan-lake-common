//! `swl env`: the consumers' `.envrc.local` files and the workspace wrappers.

use std::{
    ffi::OsStr,
    fs,
    os::unix::{ffi::OsStrExt, fs::PermissionsExt},
    path::Path,
};

use anyhow::{Context, Result, bail};

use crate::{
    config::Config,
    shim::Tool,
    workspace::{Override, Workspace, overrides_summary},
};

/// First-line marker of every file `swl env` writes; a `.envrc.local`
/// without it is hand-written and kept unless `--force`.
pub const GENERATED_MARKER: &str = "# Generated by `swl env`";

pub fn shell_quote(s: &OsStr) -> String {
    let bytes = s.as_bytes();
    let plain = !bytes.is_empty()
        && bytes
            .iter()
            .all(|b| b.is_ascii_alphanumeric() || b"@%+=:,./_-".contains(b));
    if plain {
        return s.to_string_lossy().into_owned();
    }
    format!("'{}'", s.to_string_lossy().replace('\'', r"'\''"))
}

fn q(s: impl AsRef<OsStr>) -> String {
    shell_quote(s.as_ref())
}

/// The `.envrc.local` of a consumer, following the swan-lake `.envrc`
/// contract: it is sourced before `use flake`, appends to the bash array
/// `use_flake_args`, and may call `watch_file` and `PATH_add`.
pub fn envrc_local(ws: &Workspace, overrides: &[Override]) -> String {
    let mut s = format!(
        "{GENERATED_MARKER} for the workspace {}; rerun it rather than editing.\n",
        ws.root.display()
    );
    if !overrides.is_empty() {
        s.push_str("use_flake_args+=(\n");
        for o in overrides {
            s.push_str(&format!(
                "  --override-input {} {}\n",
                q(&o.input_path),
                q(o.url())
            ));
        }
        s.push_str("  --no-write-lock-file\n)\n");
        // The sibling flakes' Nix files, so that edits reload the shell.
        // Their git index is not watched: any `git status` would reload.
        s.push_str("shopt -s globstar\n");
        let mut seen = Vec::new();
        for o in overrides {
            if seen.contains(&&o.dir) {
                continue;
            }
            seen.push(&o.dir);
            let d = q(&o.dir);
            s.push_str(&format!(
                "watch_file {d}/flake.nix {d}/flake.lock {d}/**/*.nix\n"
            ));
        }
    }
    s.push_str(&format!("PATH_add {}\n", q(ws.wrapper_dir())));
    if !overrides.is_empty() {
        s.push_str(&format!(
            "export SWAN_LAKE_OVERRIDES={}\n",
            q(overrides_summary(overrides))
        ));
    }
    s
}

pub fn wrapper(swl: &Path, ws: &Workspace, tool: Tool) -> String {
    format!(
        "#!/bin/sh\n{GENERATED_MARKER}; rerun it rather than editing.\nexec {} shim {} --workspace {} -- \"$@\"\n",
        q(swl),
        tool.name(),
        q(&ws.root)
    )
}

/// Writes `contents` unless the file already has them, so that unchanged
/// files keep their mtime and direnv does not reload. Returns whether it
/// wrote.
fn write_if_changed(path: &Path, contents: &str, mode: u32) -> Result<bool> {
    if fs::read(path).is_ok_and(|old| old == contents.as_bytes()) {
        return Ok(false);
    }
    let tmp = path.with_extension("swl-tmp");
    fs::write(&tmp, contents).with_context(|| format!("writing {}", tmp.display()))?;
    fs::set_permissions(&tmp, fs::Permissions::from_mode(mode))?;
    fs::rename(&tmp, path).with_context(|| format!("writing {}", path.display()))?;
    Ok(true)
}

fn is_generated(path: &Path) -> Result<bool> {
    match fs::read_to_string(path) {
        Ok(text) => Ok(text.starts_with(GENERATED_MARKER)),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(true),
        Err(e) => Err(e).with_context(|| format!("reading {}", path.display())),
    }
}

pub fn run(ws: &Workspace, config: &Config, swl: &Path, force: bool) -> Result<()> {
    let consumers: Vec<_> = ws.checkouts.iter().filter(|c| c.is_consumer()).collect();
    if consumers.is_empty() {
        bail!(
            "no consumer checkout (a flake directory without @ in its name) in {}",
            ws.root.display()
        );
    }
    // Check every target first, so that a refusal writes nothing.
    let mut plans = Vec::new();
    for c in consumers {
        let path = c.dir.join(".envrc.local");
        if !force && !is_generated(&path)? {
            bail!(
                "{} was not written by swl env; move it away or pass --force",
                path.display()
            );
        }
        let overrides = ws.overrides_for(config, c)?;
        plans.push((c, path, overrides));
    }
    let bin = ws.wrapper_dir();
    fs::create_dir_all(&bin).with_context(|| format!("creating {}", bin.display()))?;
    for tool in Tool::ALL {
        write_if_changed(&bin.join(tool.name()), &wrapper(swl, ws, tool), 0o755)?;
    }
    for (c, path, overrides) in plans {
        let changed = write_if_changed(&path, &envrc_local(ws, &overrides), 0o644)?;
        let summary = if overrides.is_empty() {
            "no overrides".to_string()
        } else {
            overrides_summary(&overrides)
        };
        println!(
            "{}: {summary}{}",
            c.name,
            if changed { "" } else { " (unchanged)" }
        );
        let envrc = fs::read_to_string(c.dir.join(".envrc")).unwrap_or_default();
        if !envrc.contains(".envrc.local") || !envrc.contains("use_flake_args") {
            eprintln!(
                "swl env: warning: {}/.envrc does not source .envrc.local into use_flake_args",
                c.name
            );
        }
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use std::path::PathBuf;

    use super::*;

    fn ws() -> Workspace {
        Workspace {
            root: PathBuf::from("/w s"),
            checkouts: Vec::new(),
        }
    }

    #[test]
    fn envrc_local_contract() {
        let o = |p: &str, c: &str| Override {
            input_path: p.into(),
            checkout: c.into(),
            dir: PathBuf::from("/w s").join(c),
        };
        let text = envrc_local(
            &ws(),
            &[
                o("common", "swan-lake-common@common"),
                o("common/zwanenzang", "zwanenzang@zwanenzang"),
            ],
        );
        assert_eq!(
            text,
            "\
# Generated by `swl env` for the workspace /w s; rerun it rather than editing.
use_flake_args+=(
  --override-input common 'git+file:///w s/swan-lake-common@common'
  --override-input common/zwanenzang 'git+file:///w s/zwanenzang@zwanenzang'
  --no-write-lock-file
)
shopt -s globstar
watch_file '/w s/swan-lake-common@common'/flake.nix '/w s/swan-lake-common@common'/flake.lock '/w s/swan-lake-common@common'/**/*.nix
watch_file '/w s/zwanenzang@zwanenzang'/flake.nix '/w s/zwanenzang@zwanenzang'/flake.lock '/w s/zwanenzang@zwanenzang'/**/*.nix
PATH_add '/w s/.swl/bin'
export SWAN_LAKE_OVERRIDES='common←swan-lake-common@common common/zwanenzang←zwanenzang@zwanenzang'
"
        );
        assert_eq!(
            envrc_local(&ws(), &[]),
            "# Generated by `swl env` for the workspace /w s; rerun it rather than editing.\nPATH_add '/w s/.swl/bin'\n"
        );
    }

    #[test]
    fn wrapper_is_one_exec_line() {
        assert_eq!(
            wrapper(Path::new("/nix/store/x-swl/bin/swl"), &ws(), Tool::Nh),
            "#!/bin/sh\n# Generated by `swl env`; rerun it rather than editing.\nexec /nix/store/x-swl/bin/swl shim nh --workspace '/w s' -- \"$@\"\n"
        );
    }

    #[test]
    fn quoting() {
        assert_eq!(shell_quote(OsStr::new("a@b/c")), "a@b/c");
        assert_eq!(shell_quote(OsStr::new("it's")), r"'it'\''s'");
        assert_eq!(shell_quote(OsStr::new("")), "''");
    }
}
